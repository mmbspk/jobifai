import { test, expect } from '@playwright/test'
import { registerAndInjectTokens, persistManualReview } from './helpers/auth'

test('off hides desktop review, gates the route and preserves independent lists', async ({ page, request }) => {
  const user = await registerAndInjectTokens(page, request)
  const headers = { Authorization: 'Bearer ' + user.accessToken }
  await persistManualReview(request, user, false)
  expect((await request.post('/api/e2e/seed-jobs', { headers })).ok()).toBeTruthy()
  // Isolate the waiting state without starting a real bot run.
  await page.route('**/api/bot/status', route => route.fulfill({ json: { state: 'pending_review', today_count: 2, daily_limit: 5 } }))
  const pendingRequests: string[] = []
  page.on('request', req => { if (req.url().includes('/bot/review/pending')) pendingRequests.push(req.url()) })
  await page.goto('/review')
  await expect(page).toHaveURL('/')
  await expect(page.getByText('Automation is waiting', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Stop automation' })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toHaveCount(0)
  await expect(page.getByText('Awaiting review')).toHaveCount(0)
  await expect(page.locator('a[href="/review"]')).toHaveCount(0)
  await expect(page.getByRole('link', { name: /Saved documents/ })).toBeVisible()
  for (const name of ['Applied', 'Skipped', 'Cannot Apply', 'Top Matches']) {
    await expect(page.locator('aside').getByRole('link', { name, exact: true })).toBeVisible()
  }
  await page.locator('aside').getByRole('link', { name: 'Cannot Apply', exact: true }).click()
  await expect(page.getByText('Manual Steps Co')).toBeVisible()
  await page.reload()
  await expect(page.locator('a[href="/review"]')).toHaveCount(0)
  expect(pendingRequests).toHaveLength(0)
  const queue = await request.get('/api/bot/review/pending', { headers })
  expect((await queue.json()).map((job: { job_id: string }) => job.job_id)).toContain('e2e-pending-1')
})

test('saved off/on and refresh restore the same queue with its actions', async ({ page, request }) => {
  const user = await registerAndInjectTokens(page, request)
  await persistManualReview(request, user, true)
  expect((await request.post('/api/e2e/seed-jobs', { headers: { Authorization: 'Bearer ' + user.accessToken } })).ok()).toBeTruthy()
  await page.goto('/')
  await expect(page.getByText('Awaiting review')).toBeVisible()
  await page.goto('/settings/application')
  const toggle = page.getByRole('switch', { name: 'Review before submission' })
  await expect(toggle).toBeChecked()
  await toggle.click()
  await expect(page.locator('aside').getByRole('link', { name: /^Review/ })).toBeVisible()
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.locator('a[href="/review"]')).toHaveCount(0)
  await page.reload()
  await expect(toggle).not.toBeChecked()
  await toggle.click()
  await expect(page.locator('a[href="/review"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Save changes' }).click()
  await page.locator('aside').getByRole('link', { name: /^Review/ }).click()
  await expect(page.getByText('Review Gate Inc')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Prepare documents', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Approve application' })).toBeDisabled()
  await page.getByRole('button', { name: 'Reject', exact: true }).click()
  await expect(page.getByText("You're all caught up")).toBeVisible()
})

test('mobile review tab and header bell follow saved settings without overflow', async ({ page, request }) => {
  const user = await registerAndInjectTokens(page, request)
  await page.setViewportSize({ width: 390, height: 844 })
  await persistManualReview(request, user, false)
  await page.goto('/')
  await expect(page.getByLabel('Open review queue')).toHaveCount(0)
  await expect(page.locator('nav').getByRole('link', { name: 'Review', exact: true })).toHaveCount(0)
  await page.locator('nav').getByRole('button', { name: 'Jobs', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Cannot Apply', exact: true })).toBeVisible()
  await page.goto('/settings/application')
  const toggle = page.getByRole('switch', { name: 'Review before submission' })
  await expect(toggle).toBeEnabled()
  await toggle.click()
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByLabel('Open review queue')).toBeVisible()
  await expect(page.locator('nav').getByRole('link', { name: 'Review', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Open review queue')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

test('a new login never inherits enabled review or another account queue', async ({ page, request }) => {
  const first = await registerAndInjectTokens(page, request)
  await persistManualReview(request, first, true)
  await request.post('/api/e2e/seed-jobs', { headers: { Authorization: 'Bearer ' + first.accessToken } })
  await page.goto('/review')
  await expect(page.getByText('Review Gate Inc')).toBeVisible()
  await page.locator('aside').getByRole('button', { name: 'Sign out' }).click()
  await expect(page).toHaveURL(/login/)
  const second = await registerAndInjectTokens(page, request)
  await persistManualReview(request, second, false)
  await page.goto('/review')
  await expect(page).toHaveURL('/')
  await expect(page.locator('a[href="/review"]')).toHaveCount(0)
  await expect(page.getByText('Review Gate Inc')).toHaveCount(0)
})
